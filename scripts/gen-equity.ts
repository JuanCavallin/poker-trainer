/**
 * Generates the 169x169 preflop class-vs-class all-in equity table (Monte Carlo over compatible combo
 * pairs and random boards) and writes src/engine/data/preflopEquity.ts.
 * Run: npm run gen:equity (rewrites the table; takes ~2.5 minutes)
 */
import { writeFileSync } from 'node:fs';
import { NUM_CLASSES, classCombos, comboC1, comboC2 } from '../src/engine/combos';
import { evaluate } from '../src/engine/evaluator';
import { Rng } from '../src/engine/rng';

const SAMPLES = Number(process.env.SAMPLES ?? 20000);
const rng = new Rng(20261013);
const eq = new Float64Array(NUM_CLASSES * NUM_CLASSES);
const cards = new Int32Array(7);
const deck = new Int32Array(52);
const t0 = Date.now();

for (let a = 0; a < NUM_CLASSES; a++) {
  eq[a * NUM_CLASSES + a] = 0.5;
  for (let b = a + 1; b < NUM_CLASSES; b++) {
    const pairs: [number, number][] = [];
    for (const x of classCombos[a]) {
      for (const y of classCombos[b]) {
        const xa = comboC1[x], xb = comboC2[x], ya = comboC1[y], yb = comboC2[y];
        if (xa === ya || xa === yb || xb === ya || xb === yb) continue;
        pairs.push([x, y]);
      }
    }
    let win = 0;
    for (let s = 0; s < SAMPLES; s++) {
      const [x, y] = pairs[s % pairs.length];
      const h1 = comboC1[x], h2 = comboC2[x], v1 = comboC1[y], v2 = comboC2[y];
      let n = 0;
      for (let c = 0; c < 52; c++) if (c !== h1 && c !== h2 && c !== v1 && c !== v2) deck[n++] = c;
      for (let k = 0; k < 5; k++) {
        const j = k + rng.int(n - k);
        const tmp = deck[k];
        deck[k] = deck[j];
        deck[j] = tmp;
        cards[k] = deck[k];
      }
      cards[5] = h1;
      cards[6] = h2;
      const sa = evaluate(cards, 7);
      cards[5] = v1;
      cards[6] = v2;
      const sb = evaluate(cards, 7);
      win += sa > sb ? 1 : sa === sb ? 0.5 : 0;
    }
    eq[a * NUM_CLASSES + b] = win / SAMPLES;
    eq[b * NUM_CLASSES + a] = 1 - win / SAMPLES;
  }
  if (a % 13 === 12) console.log(`row ${a + 1}/169 · ${((Date.now() - t0) / 1000).toFixed(0)}s`);
}

const u16 = new Uint16Array(NUM_CLASSES * NUM_CLASSES);
for (let i = 0; i < u16.length; i++) u16[i] = Math.round(eq[i] * 65535);
const b64 = Buffer.from(u16.buffer).toString('base64');
const lines = b64.match(/.{1,120}/g)!.map((l) => `  '${l}'`).join(',\n');
writeFileSync(
  'src/engine/data/preflopEquity.ts',
  `// Generated by scripts/gen-equity.ts (${SAMPLES} Monte Carlo samples per class pair). Do not edit.\n` +
    `/** 169x169 all-in equity of row class vs column class, as little-endian uint16 (x / 65535), base64. */\n` +
    `export const PREFLOP_EQUITY_B64 = [\n${lines},\n].join('');\n`,
);
console.log(`done in ${((Date.now() - t0) / 1000).toFixed(0)}s`);
