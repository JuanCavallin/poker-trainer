/**
 * Solves the preflop model and writes src/engine/data/preflopSolution.ts:
 *  1. Opening ranges: start from standard 6-max charts, then repeatedly (a) solve every heads-up game
 *     between the opener and each seat behind and (b) open exactly the hands whose value against
 *     the whole field beats folding, until the ranges settle.
 *  2. The heads-up equilibrium strategies for all 15 seat pairs with those opening ranges.
 * Run: npm run gen:preflop (about 20 seconds; rerun after changing the preflop model)
 */
import { writeFileSync } from 'node:fs';
import { NUM_CLASSES, classCombos, classLabel } from '../src/engine/combos';
import { OPENERS, matchup, openEv, respondersAfter, solvePair, type Position } from '../src/engine/preflop';
import { parseRange } from '../src/engine/range';

const START: Record<string, string> = {
  UTG: '55+, A2s+, K9s+, Q9s+, J9s+, T8s+, 98s, 87s, 76s, 65s, AJo+, KJo+',
  HJ: '44+, A2s+, K8s+, Q9s+, J9s+, T8s+, 97s+, 86s+, 75s+, 65s, 54s, ATo+, KJo+, QJo',
  CO: '22+, A2s+, K5s+, Q8s+, J8s+, T7s+, 97s+, 86s+, 75s+, 64s+, 54s, A8o+, A5o, KTo+, QTo+, JTo',
  BTN: '22+, A2s+, K2s+, Q4s+, J6s+, T6s+, 96s+, 85s+, 75s+, 64s+, 54s, A2o+, K8o+, Q9o+, J9o+, T8o+, 98o',
  SB: '22+, A2s+, K2s+, Q2s+, J4s+, T6s+, 96s+, 85s+, 74s+, 64s+, 53s+, 43s, A2o+, K5o+, Q8o+, J8o+, T8o+, 98o, 87o',
};
const ROUNDS = Number(process.env.ROUNDS ?? 8);

function toClasses(text: string): Float64Array {
  const r = parseRange(text);
  return Float64Array.from({ length: NUM_CLASSES }, (_, c) => classCombos[c].reduce((s, id) => s + r[id], 0) / classCombos[c].length);
}
const share = (w: ArrayLike<number>) => {
  let m = 0;
  for (let c = 0; c < NUM_CLASSES; c++) m += w[c] * classCombos[c].length;
  return m / 1326;
};

const t0 = Date.now();
const charts = new Map<Position, Float64Array>(OPENERS.map((p) => [p, toClasses(START[p])]));
for (let round = 1; round <= ROUNDS; round++) {
  const step = round <= 3 ? 0.6 : 0.35;
  const parts: string[] = [];
  for (const o of OPENERS) {
    const chart = charts.get(o)!;
    const sols = respondersAfter(o).map((r) => {
      const sol = solvePair(matchup(o, r), chart, { maxIter: 1200, targetPct: 0.05 });
      return { responder: r, sol, strat: sol.strat, heroMode: 'br' as const };
    });
    const ev = openEv(sols);
    // Soft step toward "open iff opening beats folding", so near-zero hands settle into mixes.
    const next = Float64Array.from(chart, (w, c) => (1 - step) * w + step * (1 / (1 + Math.exp(-ev[c] / 0.02))));
    charts.set(o, next);
    parts.push(`${o} ${(100 * share(next)).toFixed(1)}%`);
  }
  console.log(`round ${round}: ${parts.join(' · ')} · ${((Date.now() - t0) / 1000).toFixed(0)}s`);
}

const q = (x: number) => Math.max(0, Math.min(255, Math.round(x * 255)));
const rfi: Record<string, number[]> = {};
for (const o of OPENERS) {
  const c = charts.get(o)!.map((x) => (x < 0.02 ? 0 : x > 0.98 ? 1 : x));
  rfi[o] = Array.from(c, q);
}

const pairs: Record<string, number[][]> = {};
for (const o of OPENERS) {
  for (const r of respondersAfter(o)) {
    const m = matchup(o, r);
    const sol = solvePair(m, Float64Array.from(rfi[o], (x) => x / 255), { maxIter: 3000, targetPct: 0.01 });
    const g = sol.game;
    pairs[`${o}-${r}`] = [g.ids.vsOpen, g.ids.vs3bet, g.ids.vs4bet, g.ids.vsJam].map((id) => Array.from(sol.strat(id), q));
    const s = sol.strat(g.ids.vsOpen);
    let fold = 0;
    let call = 0;
    let raise = 0;
    for (let c = 0; c < NUM_CLASSES; c++) {
      const n = classCombos[c].length;
      fold += s[c] * n;
      call += s[NUM_CLASSES + c] * n;
      raise += s[2 * NUM_CLASSES + c] * n;
    }
    console.log(`${o} vs ${r}: fold ${(fold / 13.26).toFixed(0)}% call ${(call / 13.26).toFixed(0)}% 3bet ${(raise / 13.26).toFixed(1)}%`);
  }
}

const show = (o: string) =>
  Array.from({ length: 13 }, (_, row) =>
    Array.from({ length: 13 }, (_, col) => {
      const c = row * 13 + col;
      const v = rfi[o][c] / 255;
      return (v > 0.9 ? classLabel(c) : v > 0.1 ? classLabel(c).toLowerCase() : '.').padEnd(4);
    }).join(''),
  ).join('\n');
for (const o of OPENERS) console.log(`\n${o} opens ${(100 * share(rfi[o].map((x) => x / 255))).toFixed(1)}%\n${show(o)}`);

const body = (obj: Record<string, unknown>) => JSON.stringify(obj).replace(/\],"/g, '],\n    "');
writeFileSync(
  'src/engine/data/preflopSolution.ts',
  `// Generated by scripts/gen-preflop.ts. Do not edit.\n` +
    `/** Opening frequencies (x/255 per hand class) and heads-up strategies per seat pair: [vs open, vs 3-bet, vs 4-bet, vs jam], each actions x 169. */\n` +
    `export const PREFLOP_SOLUTION: { rfi: Partial<Record<string, number[]>>; pairs: Partial<Record<string, number[][]>> } = {\n` +
    `  rfi: ${body(rfi)},\n  pairs: ${body(pairs)},\n};\n`,
);
console.log(`\nwrote preflopSolution.ts in ${((Date.now() - t0) / 1000).toFixed(0)}s`);
